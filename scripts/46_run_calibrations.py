"""Registered calibrations not run with the discovery runs (PI ruling R4; disclosure D8). One run per entry, on A.

  H3a / H3b   matched random gene sets (R = 10 per coarse unit) and 100 dispersed never-expressed sets, scored per
              context with the context's removals and covariates; H3b also the CN segment-matched null for its
              copy-number contexts. Pre-declared response (registry): if the pseudo-context fraction (here: the
              segment-matched pseudo-contexts of the CN contexts) exceeds 0.075, every real test of those contexts with
              raw p < 0.01 not yet permutation re-tested is re-tested (Freedman-Lane, 10,000, seed permutation + row,
              as run_association) and BB is re-run -> discovery_calibrated. Random / never-expressed sets: reported.
  H2          random member splits of the same parents (size of s preserved; R = 20 per tested sub-module; seed 4800)
              and the H3a/H3b pseudo-contexts (as generated by the discovery runs' calibration), both run through the
              stage-wise machinery (BH within each eligible (context, parent) family at its level). Reported.
Writes results/part2/directions/<ID>/calibration_D8.json (+ calibration_D8_tests.tsv.gz). Refuses a second run.
Usage: .venv/bin/python scripts/46_run_calibrations.py --id H3a_lineage_atlas|H3b_driver_family|H2_submodule_divergence
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import resource
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from part2 import assoc, calib, covariates as covmod, cscore, h2, paths, registry, robust, stats  # noqa: E402

spec = importlib.util.spec_from_file_location("run_direction", ROOT / "scripts" / "44_run_direction.py")
R = importlib.util.module_from_spec(spec)
sys.modules["run_direction"] = R
spec.loader.exec_module(R)

R_SETS = 10
N_NEVER = 100
R_SPLITS = 20
SEG_FILES = ["data_cache/part2/contexts/segment_matrix.parquet", "results/part2/contexts/segments_ge8.tsv"]
SEG_EVENT = {"9p21_loss": ("homdel", "MTAP"), "MYC_amp": ("highamp", "MYC"), "MYCN_amp": ("highamp", "MYCN")}


def frac(p):
    p = np.asarray(p, float)
    p = p[np.isfinite(p)]
    return dict(n_tests=int(len(p)), frac_p_lt_005=float(np.mean(p < 0.05)) if len(p) else None,
                frac_p_lt_001=float(np.mean(p < 0.01)) if len(p) else None)


def alt_of(entry, c):
    return {"+": "less", "-": "greater", "two-sided": "two-sided"}[registry.contexts_of(entry)[c]["sign"]]


def h3(env, aid, out, rows):
    entry, _ = R.entry_of(env, aid)
    q = float(entry["fdr_family"]["q"])
    seed = int(entry["calibration"]["seed"])
    ctxs = R.primary_contexts(entry)
    units = env.fmap.coarse()
    covs, _ = covmod.per_context(entry, ctxs, env.cov)
    ess = calib.clip_essentiality(env.E_A)
    ps = R.load_pair_scores(env.proj.root)
    real = R.committed_discovery(env, aid)
    # ---- matched random sets
    sets, st = calib.matched_random_sets(env.E_A, env.fmap, units, ess, ps, R_SETS, seed)
    out["matched_random_sets"] = dict(R_per_unit=R_SETS, seed=f"default_rng([{seed}, unit index])",
                                      status=st.status.value_counts().to_dict(), n_sets=len(sets))
    of = {k: k.split("#")[0] for k in sets}
    per, allp, fam, spec_rows = {}, [], [], []
    cache = {}
    for c in ctxs:
        rem = cscore.removal_for_context(c, env.homdel.get(c))
        if rem not in cache:
            cache[rem] = calib.score_sets(env.E_A, sets, rem, env.annot)
        f = calib.test_columns(cache[rem], env.ctx[c], covs[c], alt_of(entry, c))
        rr = real[(real.context == c) & real.evaluable]
        per[c] = dict(random=frac(f.p), real=frac(rr.p))
        allp.append(f.p.values)
        fam.append(np.full(len(f), c, dtype=object))
        tmax = f.t.abs().groupby(pd.Series(of)).max()
        for r in rr[rr.discovery].itertuples(index=False):
            m = tmax.get(r.unit, np.nan)
            spec_rows.append(dict(context=c, unit=r.unit, abs_t=abs(r.t), max_abs_t_matched=m,
                                  exceeds_all_matched=bool(np.isfinite(m) and abs(r.t) > m)))
        for k, v in f.iterrows():
            rows.append(dict(calibration="matched_random_set", context=c, set=k, unit=of[k], t=v.t, p=v.p))
    p = np.concatenate(allp)
    out["matched_random_sets"].update(pooled=frac(p), real_pooled=frac(real.loc[real.evaluable, "p"]),
                                      bb=calib.bb_rejections(p, np.concatenate(fam), q), per_context=per)
    sp = pd.DataFrame(spec_rows)
    out["matched_random_sets"]["discoveries_exceeding_all_matched_sets"] = dict(
        n=int(sp.exceeds_all_matched.sum()), of=int(len(sp)),
        n_without_sets=int(sp.max_abs_t_matched.isna().sum()))
    # ---- dispersed never-expressed sets
    from part2 import contexts as cx
    expr_A, _ = cx.read_omics(paths.OMICS_EXPR, list(env.E_A.index))
    pool = calib.never_expressed_pool(expr_A, env.E_A.columns, env.annot)
    rng = np.random.default_rng([seed, 1_000_000])
    sizes = rng.choice([len(env.fmap.members[u]) for u in units], N_NEVER)
    nsets = calib.dispersed_sets(pool, sizes, env.annot, rng)
    allp, fam = [], []
    for c in ctxs:
        rem = cscore.removal_for_context(c, env.homdel.get(c))
        f = calib.test_columns(calib.score_sets(env.E_A, nsets, rem, env.annot), env.ctx[c], covs[c], alt_of(entry, c))
        allp.append(f.p.values)
        fam.append(np.full(len(f), c, dtype=object))
        for k, v in f.iterrows():
            rows.append(dict(calibration="never_expressed", context=c, set=k, unit="", t=v.t, p=v.p))
    p = np.concatenate(allp)
    out["never_expressed_sets"] = dict(n_sets=len(nsets), pool=len(pool), seed=f"default_rng([{seed}, 1000000])",
                                       sizes_min_max=[int(min(sizes)), int(max(sizes))], expected_frac=0.05,
                                       pooled=frac(p), bb=calib.bb_rejections(p, np.concatenate(fam), q),
                                       expr_file_sha256=assoc._sha_file(next((ROOT / "data_cache/part2/contexts/raw")
                                                                             .glob("OmicsExpression*.parquet"))))
    # ---- CN segment-matched null (H3b)
    if aid.startswith("H3b"):
        assoc.check_frozen(env.proj, SEG_FILES, ["results/part2/lockbox/manifest.json"] + list(entry["frozen_inputs"]))
        seg_tab = pd.read_csv(ROOT / SEG_FILES[1], sep="\t")
        seg_A = pd.read_parquet(ROOT / SEG_FILES[0]).reindex(env.E_A.index)
        items = {c["id"]: c for c in entry["context_family"]["contexts"]}
        allp, fam, seg_out = [], [], {}
        for c in [c for c in ctxs if c in SEG_EVENT]:
            ev, gene = SEG_EVENT[c]
            pcs, near = calib.segment_pseudo_contexts(seg_tab, seg_A, gene, ev, int(items[c]["n_A"]), env.annot)
            if pcs.shape[1] > 100:
                keep = np.random.default_rng([seed, 2_000_000]).permutation(pcs.shape[1])[:100]
                pcs = pcs.iloc[:, sorted(keep)]
            ps_c = []
            for s in pcs.columns:
                Y, _, _ = cscore.unit_scores(env.E_A, env.fmap, units, cscore.Removal(extra=tuple(near[s])), env.annot)
                f = calib.test_columns(Y, pcs[s], covs[c], alt_of(entry, c))
                ps_c.append(f.p.values)
                allp.append(f.p.values)
                fam.append(np.full(len(f), s, dtype=object))
            seg_out[c] = dict(event=ev, n_target=int(items[c]["n_A"]), n_segments=int(pcs.shape[1]),
                              segments=list(pcs.columns), **frac(np.concatenate(ps_c) if ps_c else []))
        p = np.concatenate(allp) if allp else np.array([])
        pooled = frac(p)
        fires = bool(pooled["frac_p_lt_005"] is not None and pooled["frac_p_lt_005"] > R.CAL_THRESHOLD)
        out["segment_null"] = dict(per_context=seg_out, pooled=pooled, threshold=R.CAL_THRESHOLD,
                                   bb=calib.bb_rejections(p, np.concatenate(fam), q) if len(p) else None,
                                   response_fires=fires)
        if fires:
            out["segment_null"]["response"] = respond(env, entry, real, [c for c in seg_out if seg_out[c]["n_segments"]],
                                                      covs, aid)


def respond(env, entry, real, cn_ctxs, covs, aid):
    """Registered response for the CN pseudo-contexts: re-test every real CN-context test with p < 0.01 not yet
    permutation re-tested (same rule and seed as run_association), re-run BB -> discovery_calibrated."""
    res = real.copy()
    perm_seed = int(entry["seeds"]["permutation"])
    units = env.fmap.coarse()
    todo = res.index[res.context.isin(cn_ctxs) & res.evaluable & (res.p < R.CAL_RAW_P) & res.p_perm.isna()]
    for i in todo:
        r = res.loc[i]
        Y, _, _ = cscore.unit_scores(env.E_A, env.fmap, units, cscore.removal_for_context(r.context), env.annot)
        X, _, ok = assoc._design(env.ctx[r.context].reindex(Y.index), covs[r.context].reindex(Y.index))
        y = Y[r.unit].values[ok]
        m = ~np.isnan(y)
        ids = Y.index[ok][m]
        st = env.strata.reindex(ids).fillna("NA").astype(str).values
        res.loc[i, "p_perm"] = assoc.permutation_p(y[m], X[m], ids, r.alternative, R.N_PERM,
                                                   np.random.default_rng(perm_seed + int(i)), env.blocks, st)
    res["p_final"] = res.p.where(res.p_perm.isna(), res.p_perm)
    adj, rej, _ = assoc._fdr(res, "p_final", entry["fdr_family"], None)
    res["q_calibrated"], res["discovery_calibrated"] = adj, rej
    od = env.proj.results_dir / "directions" / aid
    R.tsv_gz(res[res.discovery | res.discovery_calibrated], od / "discoveries_calibrated.tsv.gz")
    prim, cal = res.discovery.astype(bool), res.discovery_calibrated.astype(bool)
    return dict(n_retested=int(len(todo)), n_discovery_primary=int(prim.sum()), n_discovery_calibrated=int(cal.sum()),
                gained=int((cal & ~prim).sum()), lost=int((prim & ~cal).sum()))


def h2_calib(env, aid, out, rows):
    entry, _ = R.entry_of(env, aid)
    real = R.committed_discovery(env, aid)
    parents = {"H3a": R.committed_discovery(env, "H3a_lineage_atlas"),
               "H3b": R.committed_discovery(env, "H3b_driver_family")}
    subs = h2.h2_units(env.fmap)
    sel = assoc.parent_selection_from(parents, {s: env.fmap.parent[s] for s in subs}, q=float(entry["fdr_family"]["q"]))
    ctxs = R.primary_contexts(entry)
    cov2, _ = covmod.per_context(entry, ctxs, env.cov)
    tested = real[real.evaluable & real.eligible.astype(bool)]
    seed = int(entry["calibration"]["seed"])
    # ---- random member splits
    rep = {}
    for r in tested.itertuples(index=False):
        ci, si = ctxs.index(r.context), subs.index(r.unit)
        rem = cscore.removal_for_context(r.context, env.homdel.get(r.context))
        Ys = calib.random_split_scores(env.E_A, env.fmap, r.unit, rem, env.annot, R_SPLITS,
                                       np.random.default_rng([seed, si, ci]))
        f = calib.test_columns(Ys, env.ctx[r.context], cov2[r.context], r.alternative)
        for k, (nm, v) in enumerate(f.iterrows()):
            rep.setdefault(k, []).append(dict(context=r.context, parent=r.parent, p=v.p))
            rows.append(dict(calibration="random_split", context=r.context, set=nm, unit=r.unit, t=v.t, p=v.p))
    rej, allp = [], []
    for k, lst in rep.items():
        d = pd.DataFrame(lst)
        allp.append(d.p.values)
        n = 0
        for (c, pa), g in d.groupby(["context", "parent"]):
            pv = g.p.values
            if np.isfinite(pv).any():
                n += int(stats.bh(np.where(np.isfinite(pv), pv, 1.0), sel["level"][c])[0].sum())
        rej.append(n)
    out["random_splits"] = dict(R=R_SPLITS, seed=f"default_rng([{seed}, sub index, context index])",
                                n_tested_pairs=int(len(tested)), pooled=frac(np.concatenate(allp) if allp else []),
                                stagewise_rejections_per_replicate=dict(mean=float(np.mean(rej)) if rej else None,
                                                                        max=int(max(rej)) if rej else None),
                                real=dict(n_discovery=int(real.discovery.sum()), **frac(tested.p)))
    # ---- H3 pseudo-contexts through the stage-wise machinery
    Y2, _ = h2.h2_frames(env.E_A, env.fmap, sorted(set(tested.context)),
                         lambda c: cscore.removal_for_context(c, env.homdel.get(c)), env.annot, units=subs)
    pres, n_rej = [], 0
    for paid in ("H3a_lineage_atlas", "H3b_driver_family"):
        pe, _ = R.entry_of(env, paid)
        pctx = R.primary_contexts(pe)
        pseed = int(pe["calibration"]["seed"])
        items = {c["id"]: c for c in pe["context_family"]["contexts"]}
        M = len(pctx)
        for k, c in enumerate(pctx):
            g = tested[tested.context == c]
            n = len(range(k, R.N_PSEUDO, M))
            if not len(g) or n == 0:
                continue
            lin = cscore.is_lineage_context(c, items.get(c))
            pcs = robust.pseudo_contexts(env.ctx[c], n, pseed + k, strata=None if lin else env.strata,
                                         blocks=env.blocks)
            for j in pcs:
                f = calib.test_columns(Y2[c][list(g.unit)], pcs[j], cov2[c], "two-sided")
                pres.append(f.p.values)
                for (pa), gg in g.assign(p=f.p.values).groupby("parent"):
                    pv = gg.p.values
                    if np.isfinite(pv).any():
                        n_rej += int(stats.bh(np.where(np.isfinite(pv), pv, 1.0), sel["level"][c])[0].sum())
                for u, pv in zip(g.unit, f.p.values):
                    rows.append(dict(calibration="pseudo_context", context=c, set=f"{c}|{j}", unit=u, t=np.nan, p=pv))
    out["pseudo_contexts_stagewise"] = dict(pooled=frac(np.concatenate(pres) if pres else []),
                                            stagewise_rejections=n_rej, expected="~0")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--id", required=True, choices=["H3a_lineage_atlas", "H3b_driver_family", "H2_submodule_divergence"])
    a = ap.parse_args()
    t0 = time.time()
    env = R.real_env()
    od = env.proj.results_dir / "directions" / a.id
    if (od / "calibration_D8.json").exists():
        raise SystemExit("calibration_D8.json exists: the calibration runs once")
    entry, blob = R.entry_of(env, a.id)
    assoc.check_frozen(env.proj, env.inputs, ["results/part2/lockbox/manifest.json"] + list(entry["frozen_inputs"]))
    out = dict(analysis_id=a.id, label="registered calibration run after the discovery run (D8; PI ruling R4)",
               registry_calibration=entry["calibration"], registry_blob=blob)
    rows = []
    if a.id.startswith("H3"):
        h3(env, a.id, out, rows)
    else:
        h2_calib(env, a.id, out, rows)
    out["runtime_s"] = round(time.time() - t0, 1)
    out["peak_rss_bytes"] = int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
    R.tsv_gz(pd.DataFrame(rows), od / "calibration_D8_tests.tsv.gz")
    (od / "calibration_D8.json").write_text(json.dumps(out, indent=1, sort_keys=True, default=float) + "\n")
    print(json.dumps({k: v for k, v in out.items() if k != "registry_calibration"}, indent=1, default=float)[:6000])


if __name__ == "__main__":
    main()
